// Data Store Helper Functions with localStorage caching
const STORAGE_KEY = "ALJELAH_CHARITY_SITE_DATA_V1";

function loadSiteData() {
  const defaults = JSON.parse(JSON.stringify(DEFAULT_SITE_DATA));
  if (typeof localStorage === "undefined") return defaults;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return defaults;
    const parsed = JSON.parse(raw);
    return { ...defaults, ...parsed };
  } catch (err) {
    console.warn("Could not load from localStorage, falling back to default site data:", err);
    return defaults;
  }
}

function saveSiteData(data) {
  if (typeof localStorage === "undefined") return true;
  try {
    const toSave = data !== undefined ? data : (typeof window !== "undefined" ? window.siteData : (typeof global !== "undefined" ? global.siteData : DEFAULT_SITE_DATA));
    localStorage.setItem(STORAGE_KEY, JSON.stringify(toSave));
    return true;
  } catch (err) {
    console.error("Error saving site data to localStorage:", err);
    return false;
  }
}

function resetSiteData() {
  const fresh = JSON.parse(JSON.stringify(DEFAULT_SITE_DATA));
  if (typeof localStorage !== "undefined") {
    try {
      localStorage.removeItem(STORAGE_KEY);
    } catch (err) {
      console.error("Error resetting site data:", err);
    }
  }
  const gs = typeof window !== "undefined" ? window : (typeof global !== "undefined" ? global : this);
  if (gs) gs.siteData = fresh;
  return fresh;
}

// Global accessor safe for browser and Node.js
const globalScope = typeof window !== "undefined" ? window : (typeof global !== "undefined" ? global : this);
globalScope.siteData = loadSiteData();
globalScope.saveSiteData = saveSiteData;
globalScope.resetSiteData = resetSiteData;
globalScope.DEFAULT_SITE_DATA = DEFAULT_SITE_DATA;

if (typeof module !== "undefined" && module.exports) {
  module.exports = {
    DEFAULT_SITE_DATA,
    loadSiteData,
    saveSiteData,
    resetSiteData
  };
}
